"""Draws the installer icon: a pixel-art chess king in the game's palette.

Usage: make_icon.py <icon.ico> <icon.png>
"""
import sys

from PIL import Image

DARK = (36, 40, 40, 255)
MOSS = (58, 80, 67, 255)
GREEN = (127, 152, 96, 255)
CREAM = (248, 238, 191, 255)

# 32x32 silhouette of the king; the outline is added around it.
KING = """
................................
................................
................................
...............##...............
...............##...............
.............######.............
.............######.............
...............##...............
...............##...............
.............######.............
............########............
............########............
............########............
...........##########...........
.............######.............
.............######.............
.............######.............
............########............
............########............
...........##########...........
...........##########...........
..........############..........
.........##############.........
........################........
........################........
.......##################.......
.......##################.......
................................
................................
................................
................................
................................
"""


def draw():
    rows = [r for r in KING.strip("\n").split("\n")]
    size = len(rows)
    piece = {(x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#"}
    outline = {(x + dx, y + dy) for x, y in piece for dx in (-1, 0, 1) for dy in (-1, 0, 1)} - piece

    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    radius = 4
    for y in range(size):
        for x in range(size):
            cx = min(x, size - 1 - x)
            cy = min(y, size - 1 - y)
            if cx < radius and cy < radius and (radius - cx - 0.5) ** 2 + (radius - cy - 0.5) ** 2 > radius ** 2:
                continue
            edge = cx == 0 or cy == 0
            img.putpixel((x, y), GREEN if edge else MOSS)
    for x, y in outline:
        img.putpixel((x, y), DARK)
    for x, y in piece:
        # A lighter left half gives the piece a little volume.
        img.putpixel((x, y), CREAM if x < size // 2 else (226, 214, 166, 255))
    return img


def main(ico, png):
    master = draw()
    sizes = [16, 24, 32, 48, 64, 128, 256]
    master.resize((256, 256), Image.NEAREST).save(ico, sizes=[(s, s) for s in sizes])
    master.resize((64, 64), Image.NEAREST).save(png)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
